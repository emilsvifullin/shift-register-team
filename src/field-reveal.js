/*
  Раскрытие связанных полей внутри своей же плитки.

  Раньше выбор сотрудника, ПВЗ и даты уводил человека в отдельное
  модальное окно, а дополнительные поля корректировки, аккаунта и тарифа
  жили в соседних карточках. Связь с исходной строкой держалась только на
  памяти: плитка говорила «Сотрудник», а список приезжал снизу отдельным
  окном и выглядел приклеенным.

  Здесь эта связь становится структурной: продолжение остаётся внутри
  родительской плитки и просто увеличивает её высоту.

  Высота анимируется через grid-template-rows: 0fr -> 1fr. Обычный переход
  по height требует заранее знать конечный размер, а он зависит от числа
  строк списка, от длины имён и от ширины экрана; попытка его вычислить
  даёт скачок layout на первом кадре. Строка грида доезжает до
  собственного содержимого сама, поэтому разметка не обязана знать,
  сколько места займёт раскрытое.

  Содержимое остаётся в разметке и в закрытом состоянии. Иначе свернуть
  плавно нельзя: разметка отдала бы пустое тело в том же кадре, в котором
  снимается класс, и вниз поехала бы пустая коробка. Реконсилятор
  переиспользует узлы, поэтому класс, изменившийся между отрисовками,
  запускает переход на живом узле в обе стороны. От фокуса и от
  скринридера свёрнутое продолжение закрывает inert.
*/

/*
  Длительность перехода из styles/inline-fields.css. Её знает и разметка:
  строку, которую сворачивают перед удалением, нужно убрать из данных
  ровно тогда, когда она доехала до нуля.
*/
export const REVEAL_DURATION=320;

export function fieldRevealHTML({
  key,
  open,
  body,
  className=""
}){
  return `
    <div
      class="field-reveal${open ? " on" : ""}${className ? " "+className : ""}"
      data-key="${key}"
    >
      <div
        class="field-reveal-body"
        ${open ? "" : "inert"}
      >
        ${body}
      </div>
    </div>
  `;
}
