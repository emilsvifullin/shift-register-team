/*
  Человек попросил систему двигать поменьше.

  Вопрос задают из разных мест — жест закрытия поверхности, переходы
  выбиралок, листание месяца, — и ответ везде один. Держать его копии
  в каждом модуле значит рано или поздно получить экран, где половина
  движения отключилась, а половина нет.
*/
export function prefersReducedMotion(){
  return window.matchMedia?.(
    "(prefers-reduced-motion: reduce)"
  ).matches===true;
}
