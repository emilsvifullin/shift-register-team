/*
  Распознаватель горизонтального жеста колеса — двухпальцевого свайпа по
  трекпаду.

  Трекпад присылает жест не одним событием, а россыпью мелких шагов: у
  каждого свои дробные deltaX и deltaY, а после отрыва пальцев macOS ещё
  до секунды досылает затухающий хвост инерции. Решение поэтому
  принимается по жесту целиком, а не по отдельному шагу.

  Прежний разбор был пошаговым, и на живом трекпаде это давало ровно то,
  на что жалуются: свайп срабатывал через раз.

  — Шаг, у которого вертикальная составляющая случайно перевесила
    горизонтальную, выбрасывался целиком. У настоящего свайпа такие шаги
    идут вперемешку с остальными: путь не накапливался, а отсчёт паузы не
    обновлялся, и жест разрывался на части посреди движения.
  — Направление бралось из одного шага. Крошечный шаг в обратную сторону
    в начале и в конце жеста обычен, и он считался сменой направления —
    накопленный путь обнулялся.
  — Хвост инерции не давал начаться следующему жесту: пока он шёл, свайп
    считался продолжением предыдущего и проглатывался. Пауза — например,
    тап по экрану — давала состоянию сброситься, и следующий свайп
    срабатывал. Отсюда и «сначала тапнуть, потом свайпнуть».

  Здесь ось выбирается один раз по накопленному пути, направление берётся
  оттуда же, а новый жест начинается либо после настоящей паузы, либо
  когда затихший хвост инерции сменяется новым разгоном.
*/

const DEFAULTS=Object.freeze({
  /* Сколько пройти вдоль оси, чтобы жест считался свайпом. */
  distance:48,
  /* Во сколько раз своя ось должна перевесить чужую. */
  ratio:1.2,
  /* Пауза, после которой начинается новый жест. */
  idle:180,
  /* Шаг, ниже которого хвост инерции считается затихшим. */
  quiet:2,
  /* Во сколько раз шаг должен превысить затихший хвост, чтобы считаться новым разгоном. */
  revive:2.5
});

export function createWheelGesture(options={}){
  const {
    distance,
    ratio,
    idle,
    quiet,
    revive
  }={...DEFAULTS,...options};

  let lastAt=0;
  let lastStep=0;
  let x=0;
  let y=0;
  let axis=null;
  let fired=false;
  let wentQuiet=false;

  function startGesture(){
    x=0;
    y=0;
    axis=null;
    fired=false;
    wentQuiet=false;
    lastStep=0;
  }

  /*
    Хвост инерции только затухает. Поэтому новый разгон после затишья —
    это уже рука человека, а не остаток прошлого жеста.
  */
  function restarted(step){
    if(!fired){
      return false;
    }

    if(step<quiet){
      wentQuiet=true;
      return false;
    }

    return (
      wentQuiet &&
      step>lastStep*revive
    );
  }

  return {
    /*
      Принимает один шаг колеса и отвечает, что с ним делать:

      direction — −1 или 1, когда жест только что сложился, иначе 0;
      claim — удерживать ли шаг за приложением. Вертикальную прокрутку
      приложение не удерживает: она должна остаться родной.
    */
    push({
      deltaX=0,
      deltaY=0,
      now=0
    }={}){
      const step=Math.abs(deltaX);

      if(
        !lastAt ||
        now-lastAt>idle ||
        restarted(step)
      ){
        startGesture();
      }

      lastAt=now;
      lastStep=step;

      if(axis==="y"){
        return {
          direction:0,
          claim:false
        };
      }

      x+=deltaX;
      y+=deltaY;

      const alongX=Math.abs(x);
      const alongY=Math.abs(y);

      if(axis===null){
        if(
          alongY>=distance &&
          alongY>alongX*ratio
        ){
          axis="y";

          return {
            direction:0,
            claim:false
          };
        }

        if(
          alongX>=distance &&
          alongX>alongY*ratio
        ){
          axis="x";
        }
      }

      if(axis!=="x"){
        /*
          Ось ещё не выбрана: шаг удерживается, только пока движение
          выглядит горизонтальным, иначе страница перестанет прокручиваться.
        */
        return {
          direction:0,
          claim:alongX>alongY
        };
      }

      if(fired){
        return {
          direction:0,
          claim:true
        };
      }

      fired=true;

      return {
        direction:x>0
          ? 1
          : -1,
        claim:true
      };
    },

    /* Жест снимается принудительно, когда экран сменился. */
    cancel(){
      lastAt=0;
      startGesture();
    }
  };
}
