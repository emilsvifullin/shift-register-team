-- Один номер телефона может принадлежать нескольким сотрудникам.
--
-- employees_phone_uidx требовал, чтобы номер был уникален по всей таблице.
-- В жизни это не так: мать и сын работают как разные сотрудники, а деньги
-- обоим уходят на один номер. Карточка второго просто не сохранялась.
--
-- Номер сотрудника — способ связи и реквизит перевода, а не его
-- удостоверение: по нему никто не ищет сотрудника и ничто на него не
-- ссылается. Удостоверяет сотрудника user_id аккаунта, и его уникальность
-- (employees_user_id_key) остаётся: два сотрудника не могут делить один
-- вход. Формат номера тоже остаётся — employees_phone_e164_check.
--
-- transfer_phone уникальным никогда и не был, так что для реквизитов
-- перевода ничего не меняется.
begin;

drop index if exists public.employees_phone_uidx;

commit;
